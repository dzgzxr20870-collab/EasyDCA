// ⚠️ Dashboard แบบแยกหน้า (Multi-page) ถูกเพิ่มเป็น **Route คู่ขนาน** ที่ `/app/*`
// โดยเจตนา — **ห้ามลบ/แทนที่ `/dashboard` เดิมเด็ดขาด** จนกว่าจะผ่านการใช้งานจริง
// เพราะ Rollback ต้องทำได้ทันทีด้วยการปิด Flag ตัวเดียว ไม่ต้อง Revert โค้ด
//
// ── ทำไมต้องมี Flag ทั้งที่เป็น Route คนละอันอยู่แล้ว ───────────────────────
// Route คู่ขนานกัน Rollback ได้ก็จริง แต่ "ลิงก์เข้าหน้าใหม่" ที่โผล่ใน UI เดิม
// (ปุ่ม/เมนู) คือสิ่งที่พาผู้ใช้เข้าไปเจอของที่ยังไม่พร้อม — Flag คุมตรงนั้น
// และคุม Route ด้วยพร้อมกัน จึงปิดได้ครบในสวิตช์เดียว
//
// ⚠️ อ่านจาก import.meta.env (Build-time ของ Vite) ไม่ใช่ localStorage —
// ค่านี้ไม่ใช่ "การตั้งค่าของผู้ใช้" แต่เป็น "สถานะการปล่อยฟีเจอร์ของระบบ"
// และกฎยืนห้ามใช้ localStorage กับข้อมูล Sensitive อยู่แล้ว จึงไม่เปิดช่องให้
// ผู้ใช้ Toggle เองผ่าน Storage ที่แก้ได้จาก DevTools
//
// เปิดใช้ตอน Deploy ด้วย: VITE_ENABLE_MULTIPAGE_APP=true
// (ยังไม่ตั้ง = ปิด ซึ่งคือค่าเริ่มต้นที่ปลอดภัยตอนนี้)
// Export เพื่อให้เทสต์พิสูจน์พฤติกรรม Fail-closed ได้ตรงๆ — ค่าที่ไม่ใช่ 'true'
// เป๊ะๆ ต้องแปลว่า "ปิด" ทุกกรณี รวมถึงค่าที่ "ดูเหมือนเปิด" อย่าง 'TRUE'/'1'/'yes'
// (ถ้าเผลอทำให้ค่าพวกนี้เปิดได้ Flag จะเปิดเองจากการพิมพ์ผิดบน Railway)
export function readFlag(name) {
  try {
    const env = import.meta.env ?? {};
    return env[name] === 'true' || env[name] === true;
  } catch {
    // กัน Environment ที่ไม่มี import.meta (เช่น Test Runner บางตัว) — ถือว่าปิด
    return false;
  }
}

// Dashboard แบบแยกหน้า (/app/*) — Stage 9
export const MULTIPAGE_APP_ENABLED = readFlag('VITE_ENABLE_MULTIPAGE_APP');
